#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { authenticateGeneratedContract } from "./audit-release-authority.mjs";
import { assertExternalEvidenceProducerEnabled } from "./external-evidence-producer.mjs";

const modulePath = fileURLToPath(import.meta.url);
const repositoryRoot = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const role = "npm-authority";

export const npmAuthorityCredentialInterface = Object.freeze({
  status: "unprovisioned-stop",
  requiredObservations: Object.freeze([
    "authenticated-npm-whoami-exact-account-mannyc1",
    "authenticated-empty-npm-access-token-inventory-at-registry-npmjs-org",
    "exact-sole-maintainer-mannyc1-for-eleven-public-and-one-reservation-package",
    "authenticated-publishing-access-require-two-factor-authentication-and-disallow-tokens-for-all-twelve-authority-packages",
    "authenticated-npm-trust-list-for-all-eleven-packages",
    "raw-allowed-action-projection-for-all-eleven-packages",
    "repository-and-environment-secret-name-inventories",
    "repository-and-environment-variable-name-inventories",
    "environment-policy-and-branch-policy",
    "repository-oidc-subject-policy",
  ]),
  credentialRequirements: Object.freeze([
    "ephemeral-observation-only-mannyc1-session",
    "npm-account-two-factor-authentication-required",
    "npm-package-write-permission-required-for-trust-observation",
    "not-a-github-secret-variable-workflow-input-or-artifact",
    "not-an-npm-token-environment-variable",
    "never-logged-hashed-signed-or-uploaded",
    "destroyed-before-sigstore-oidc-signing",
  ]),
  blocker: "supported-authenticated-npm-and-github-administration-observation-mechanism-not-established",
});

export const assertNpmAuthorityObservationMechanismSupported = () => {
  throw new Error(`npm authority producer STOP: ${npmAuthorityCredentialInterface.blocker}`);
};

const loadContract = async () => {
  const source = await readFile(resolve(repositoryRoot, "tooling/effect-build-contract.json"), "utf8");
  const parsed = JSON.parse(source);
  const contract = await authenticateGeneratedContract(parsed, repositoryRoot);
  if (source !== `${JSON.stringify(contract, null, 2)}\n`) {
    throw new Error("npm authority producer contract bytes are not canonical generated bytes");
  }
  return contract;
};

const main = async () => {
  const sourceSha = process.env.SOURCE_SHA;
  const outputDirectory = process.env.OUTPUT_DIRECTORY;
  if (
    typeof sourceSha !== "string"
    || !/^[0-9a-f]{40}$/u.test(sourceSha)
    || typeof outputDirectory !== "string"
    || outputDirectory.length === 0
  ) throw new Error("npm authority producer inputs are absent or invalid");
  const contract = await loadContract();

  // The current generated contract has no producer identities, so this is the
  // first STOP. A later activation cannot remove the second STOP below without
  // a reviewed, supported, non-persistent observation mechanism.
  assertExternalEvidenceProducerEnabled({ contract, role, sourceSha });
  assertNpmAuthorityObservationMechanismSupported();
};

if (process.argv[1] !== undefined && resolve(process.argv[1]) === modulePath) {
  await main();
}
