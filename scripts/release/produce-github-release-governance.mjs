#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { authenticateGeneratedContract } from "./audit-release-authority.mjs";
import { assertExternalEvidenceProducerEnabled } from "./external-evidence-producer.mjs";
import { canonicalJson, sha256Digest } from "./protocol.mjs";

const modulePath = fileURLToPath(import.meta.url);
const repositoryRoot = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const role = "github-release-governance";

export const githubReleaseGovernanceObservationInterface = Object.freeze({
  status: "unprovisioned-stop",
  endpoint: "repos/mannyc2/effect-build/immutable-releases",
  requiredPermission: "repository-administration-read",
  credentialRequirements: Object.freeze([
    "ephemeral-read-only-repository-administration-authority",
    "not-the-workflow-github-token",
    "not-a-github-secret-variable-workflow-input-or-artifact",
    "never-logged-hashed-signed-or-uploaded",
    "destroyed-before-sigstore-oidc-signing",
  ]),
  blocker: "supported-authenticated-github-administration-observation-mechanism-not-established",
});

export const assertGithubReleaseGovernanceObservationMechanismSupported = () => {
  throw new Error(
    `GitHub Release governance producer STOP: ${githubReleaseGovernanceObservationInterface.blocker}`,
  );
};

const isRecord = (value) => value !== null && typeof value === "object" && !Array.isArray(value);

const exactKeys = (value, expected, label) => {
  if (
    !isRecord(value)
    || JSON.stringify(Object.keys(value).sort()) !== JSON.stringify([...expected].sort())
  ) throw new Error(`${label} has missing or additional fields`);
  return value;
};

const fullSha = (value, label) => {
  if (typeof value !== "string" || !/^[0-9a-f]{40}$/u.test(value)) {
    throw new Error(`${label} is not one full lowercase source SHA`);
  }
  return value;
};

const canonicalTimestamp = (value, label) => {
  if (typeof value !== "string") throw new Error(`${label} is not a timestamp`);
  const milliseconds = Date.parse(value);
  if (!Number.isFinite(milliseconds) || new Date(milliseconds).toISOString() !== value) {
    throw new Error(`${label} is not one canonical UTC timestamp`);
  }
  return value;
};

export const buildGithubReleaseGovernanceReceipt = ({ contract, sourceSha, observedAt, response }) => {
  fullSha(sourceSha, "GitHub Release governance source SHA");
  canonicalTimestamp(observedAt, "GitHub Release governance observation time");
  const release = contract.releaseCertification;
  const definition = release.readiness.evidenceRoles.find((entry) => entry.role === role);
  const receiptPolicy = release.readiness.externalReceipts.githubReleaseGovernance;
  const observed = exactKeys(response, ["enabled", "enforced_by_owner"], "GitHub immutable Release response");
  if (typeof observed.enabled !== "boolean" || typeof observed.enforced_by_owner !== "boolean") {
    throw new Error("GitHub immutable Release response is not one resolved boolean decision");
  }
  const decision = receiptPolicy.decisions.find((entry) => entry.enabled === observed.enabled);
  if (!isRecord(definition) || !isRecord(decision)) {
    throw new Error("GitHub Release governance contract has no exact decision");
  }
  const endpoint = `repos/${release.githubAuthority.repository}/immutable-releases`;
  const decisionReceipt = {
    endpoint,
    enabled: observed.enabled,
    enforcedByOwner: observed.enforced_by_owner,
  };
  return {
    schema: definition.protocol,
    sourceSha,
    observedAt,
    terminal: definition.terminal,
    identity: receiptPolicy.identity,
    repository: release.githubAuthority.repository,
    endpoint,
    enabled: observed.enabled,
    decision: decision.decision,
    decisionReceiptDigest: sha256Digest(canonicalJson(decisionReceipt)),
    claims: decision.claims,
    backendAuthentication: receiptPolicy.backendAuthentication,
  };
};

export const collectGithubReleaseGovernanceReceipt = async ({
  contract,
  sourceSha,
  observedAt,
  administrationReadBoundary,
}) => {
  const repository = contract.releaseCertification.githubAuthority.repository;
  const endpoint = `repos/${repository}/immutable-releases`;
  const response = await administrationReadBoundary.readJson(endpoint);
  return buildGithubReleaseGovernanceReceipt({
    contract,
    observedAt: observedAt ?? new Date().toISOString(),
    response,
    sourceSha,
  });
};

const loadContract = async () => {
  const source = await readFile(resolve(repositoryRoot, "tooling/effect-build-contract.json"), "utf8");
  const parsed = JSON.parse(source);
  const contract = await authenticateGeneratedContract(parsed, repositoryRoot);
  if (source !== `${JSON.stringify(contract, null, 2)}\n`) {
    throw new Error("GitHub Release governance contract bytes are not canonical generated bytes");
  }
  return contract;
};

const main = async () => {
  const sourceSha = process.env.SOURCE_SHA;
  const outputDirectory = process.env.OUTPUT_DIRECTORY;
  if (
    typeof sourceSha !== "string"
    || !/^[0-9a-f]{40}$/u.test(sourceSha)
    || typeof outputDirectory !== "string"
    || outputDirectory.length === 0
  ) throw new Error("GitHub Release governance producer inputs are absent or invalid");
  const contract = await loadContract();

  // The current generated contract has no producer identities, so this is the
  // first STOP. A later activation cannot remove the second STOP below without
  // a reviewed, ephemeral repository-Administration-read observation boundary.
  assertExternalEvidenceProducerEnabled({ contract, role, sourceSha });
  assertGithubReleaseGovernanceObservationMechanismSupported();
};

if (process.argv[1] !== undefined && resolve(process.argv[1]) === modulePath) {
  await main();
}
